# Build the MuJoCo USD consumer used by `dynamics.py --engine mujoco-usd` and
# tools/view_control/check_mujoco_usd_matrix.py: a USD-enabled libmujoco, its USD
# decoder plugin, and the bounded-trajectory worker. Idempotent: re-running on an
# existing build only does what is missing.
#
# It applies the two environment fixes that are NOT part of LightUSD but are
# needed to build MuJoCo's experimental USD code against some OpenUSD builds
# (see doc/validation/physics-item7-closure-2026-11-06.md):
#   1. Namespace: an OpenUSD dist with PXR_NS != pxr (e.g. `pxr_lte`) breaks
#      MuJoCo's hardcoded `pxr::`. A forced-include header adds
#      `namespace pxr = PXR_NS;` (guarded by __has_include, so unrelated targets
#      without the USD include path are unaffected). Skipped when the build's
#      CMAKE_CXX_FLAGS already contain a pxr_alias include.
#   2. The install omits mjcPhysics/generatedSchema.usda; without it the decoder
#      aborts with "Invalid size for o_solref attribute: 0 expected 2". It is
#      copied from the MuJoCo source next to plugInfo.json.
#
# Required environment:
#   MUJOCO_SRC     MuJoCo checkout that supports -DMUJOCO_WITH_USD=ON
#   OPENUSD_DIST   OpenUSD install prefix (contains lib/cmake / pxrConfig.cmake)
# Optional environment:
#   MUJOCO_BUILD   build directory            (default: $MUJOCO_SRC/build-usd)
#   TOOLS_OUT      worker/alias output dir    (default: $MUJOCO_BUILD/lightusd-tools)
#   CMAKE_EXTRA    extra configure args, e.g. "-DFETCHCONTENT_SOURCE_DIR_LODEPNG=..."
#                  (a fresh configure fetches MuJoCo's dependencies)
#   JOBS           parallel build jobs        (default: nproc)
#   CXX            compiler for the worker    (default: c++)
#
# On success prints the exports that check_mujoco_usd_matrix.py reads:
#   LIGHTUSD_MUJOCO_WORKER, LIGHTUSD_MUJOCO_USD_PLUGIN
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"

: "${MUJOCO_SRC:?set MUJOCO_SRC to a MuJoCo checkout}"
: "${OPENUSD_DIST:?set OPENUSD_DIST to an OpenUSD install prefix}"
MUJOCO_SRC="$(cd "$MUJOCO_SRC" && pwd)"
OPENUSD_DIST="$(cd "$OPENUSD_DIST" && pwd)"
MUJOCO_BUILD="${MUJOCO_BUILD:-$MUJOCO_SRC/build-usd}"
mkdir -p "$MUJOCO_BUILD"
MUJOCO_BUILD="$(cd "$MUJOCO_BUILD" && pwd)"
TOOLS_OUT="${TOOLS_OUT:-$MUJOCO_BUILD/lightusd-tools}"
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"
mkdir -p "$TOOLS_OUT"

worker_src="$repo/tests/next/mujoco-bounded-dynamics.cc"
[[ -f "$worker_src" ]] || { echo "missing $worker_src" >&2; exit 1; }
[[ -f "$MUJOCO_SRC/CMakeLists.txt" ]] || { echo "MUJOCO_SRC is not a MuJoCo checkout" >&2; exit 1; }

# 1. Namespace shim (only when the existing build does not already carry one).
alias_h="$TOOLS_OUT/pxr_alias.h"
cat >"$alias_h" <<'EOF'
// Generated by tools/view_control/setup_mujoco_usd.sh.
// MuJoCo hardcodes `pxr::`; some OpenUSD builds define PXR_NS differently.
#pragma once
#if defined(__has_include)
#  if __has_include(<pxr/pxr.h>)
#    include <pxr/pxr.h>
#    if PXR_USE_NAMESPACES
namespace pxr = PXR_NS;
#    endif
#  endif
#endif
EOF
cxx_flags=""
if [[ -f "$MUJOCO_BUILD/CMakeCache.txt" ]]; then
  cxx_flags="$(sed -n 's/^CMAKE_CXX_FLAGS:[A-Z]*=//p' "$MUJOCO_BUILD/CMakeCache.txt")"
fi
if [[ "$cxx_flags" == *pxr_alias* ]]; then
  echo "[setup] existing CMAKE_CXX_FLAGS already include a pxr alias; leaving flags unchanged"
  flags_arg=()
else
  flags_arg=("-DCMAKE_CXX_FLAGS=${cxx_flags:+$cxx_flags }-include $alias_h")
fi

# 2. Configure (idempotent) and build the consumer targets.
echo "[setup] configuring $MUJOCO_BUILD"
# shellcheck disable=SC2086
cmake -S "$MUJOCO_SRC" -B "$MUJOCO_BUILD" -G Ninja \
  -DCMAKE_BUILD_TYPE=Release -DMUJOCO_WITH_USD=ON \
  -Dpxr_DIR="$OPENUSD_DIST" "${flags_arg[@]}" ${CMAKE_EXTRA:-}
echo "[setup] building mujoco + usd_decoder_plugin"
cmake --build "$MUJOCO_BUILD" --target mujoco usd_decoder_plugin -j "$JOBS"

lib="$MUJOCO_BUILD/lib"
plugin="$lib/libusd_decoder_plugin.so"
[[ -f "$plugin" ]] || { echo "decoder plugin not produced: $plugin" >&2; exit 1; }

# 3. Missing schema layer.
schema_src="$MUJOCO_SRC/src/experimental/usd/mjcPhysics/generatedSchema.usda"
schema_dst="$lib/mujoco-usd-resources/mjcPhysics/generatedSchema.usda"
if [[ ! -f "$schema_dst" ]]; then
  [[ -f "$schema_src" ]] || { echo "missing $schema_src" >&2; exit 1; }
  mkdir -p "$(dirname "$schema_dst")"
  cp "$schema_src" "$schema_dst"
  echo "[setup] installed mjcPhysics/generatedSchema.usda"
fi

# 4. Bounded-trajectory worker (links the USD-enabled libmujoco).
worker="$TOOLS_OUT/mujoco-bounded-dynamics"
if [[ ! -x "$worker" || "$worker_src" -nt "$worker" || "$lib/libmujoco.so" -nt "$worker" ]]; then
  echo "[setup] building worker"
  "${CXX:-c++}" -std=c++17 -O1 "$worker_src" -I"$MUJOCO_SRC/include" \
    -L"$lib" -lmujoco -Wl,-rpath,"$lib" -o "$worker"
fi

cat <<EOF

MuJoCo USD consumer ready. To run the matrix:
  export LIGHTUSD_MUJOCO_WORKER=$worker
  export LIGHTUSD_MUJOCO_USD_PLUGIN=$plugin
  python3 tools/view_control/check_mujoco_usd_matrix.py
EOF
