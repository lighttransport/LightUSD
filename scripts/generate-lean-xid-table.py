#!/usr/bin/env python3
"""Generate Lean XID tables from hash-pinned official Unicode 15.1 data.

Also compare the native C ranges against that independent reference. Fetch the
cache first with scripts/fetch-lean-unicode-data.py; --check rejects output or
native table drift. The host Python Unicode version is irrelevant.
"""
import argparse
import os
import re
import sys

from lean_unicode_ucd import DEFAULT_UCD_DIR, VERSION, property_ranges

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C_SOURCE = os.path.join(ROOT, "src", "unicode-xid-c.c")
DEFAULT_OUT = os.path.join(ROOT, "verif", "lean", "UsdSpec", "Unicode", "XidTable.lean")

TABLE_RE = re.compile(r"static const unsigned int (kXID_\w+Table)\[\]\[2\] = \{(.*?)\};", re.S)
PAIR_RE = re.compile(r"\{\s*0x([0-9a-fA-F]+)u\s*,\s*0x([0-9a-fA-F]+)u\s*\}")


def parse_tables(text):
    tables = {}
    for name, body in TABLE_RE.findall(text):
        pairs = [(int(a, 16), int(b, 16)) for a, b in PAIR_RE.findall(body)]
        if not pairs:
            raise SystemExit(f"no ranges parsed for {name}")
        # Sanity: inclusive, sorted, non-overlapping (the Lean binary search relies on it).
        for lo, hi in pairs:
            if lo > hi:
                raise SystemExit(f"{name}: inverted range {lo:#x}-{hi:#x}")
        for (_, h1), (l2, _) in zip(pairs, pairs[1:]):
            if not h1 < l2:
                raise SystemExit(f"{name}: unsorted/overlapping ranges at {h1:#x},{l2:#x}")
        tables[name] = pairs
    for required in ("kXID_StartTable", "kXID_ContinueTable"):
        if required not in tables:
            raise SystemExit(f"{required} not found in {C_SOURCE}")
    return tables


def emit_array(name, doc, pairs):
    lines = [f"/-- {doc} ({len(pairs)} inclusive ranges, sorted, disjoint). -/",
             f"def {name} : Array (UInt32 × UInt32) := #["]
    for i, (lo, hi) in enumerate(pairs):
        sep = "," if i + 1 < len(pairs) else ""
        lines.append(f"  ({lo:#x}, {hi:#x}){sep}")
    lines.append("]")
    return "\n".join(lines)


def generate(text, ucd_dir):
    native = parse_tables(text)
    start = property_ranges(ucd_dir, 'DerivedCoreProperties.txt', 'XID_Start')
    cont = property_ranges(ucd_dir, 'DerivedCoreProperties.txt', 'XID_Continue')
    for name, expected in [('kXID_StartTable', start), ('kXID_ContinueTable', cont)]:
        if native[name] != expected:
            raise SystemExit(f'{name}: native ranges differ from pinned Unicode {VERSION}')
    parts = [
        "-- Generated by scripts/generate-lean-xid-table.py. Do not edit.",
        f"-- Source: official Unicode {VERSION} DerivedCoreProperties.txt; hash-pinned manifest.",
        "/-!",
        "# Unicode XID_Start / XID_Continue tables",
        "",
        "SPEC: core_spec.md L1805-1817 (6.9 Names) and L3620-3647 (8 Path Grammar):",
        "identifiers use the `XID_Start` / `XID_Continue` classes of the Unicode",
        f"database, unmodified. These ranges come independently from Unicode {VERSION}",
        "DerivedCoreProperties.txt. The generator also checks the native ranges in",
        "src/unicode-xid-c.c against the same reference (not the reverse).",
        "-/",
        "",
        "namespace UsdSpec.Unicode",
        "",
        emit_array("xidStartRanges", "Inclusive code-point ranges of `XID_Start`", start),
        "",
        emit_array("xidContinueRanges", "Inclusive code-point ranges of `XID_Continue`", cont),
        "",
        "/-- Binary search for the first range whose upper bound is `≥ cp`; `cp` is a",
        "member when that range also starts at or below it. Mirrors `in_table` in",
        "src/unicode-xid-c.c. `fuel` bounds the loop (`tbl.size` iterations suffice,",
        "the search needs only `log2 tbl.size`). -/",
        "def rangeTableContains (tbl : Array (UInt32 × UInt32)) (cp : UInt32) : Bool :=",
        "  let rec go (lo hi : Nat) : Nat → Nat",
        "    | 0 => lo",
        "    | fuel + 1 =>",
        "      if lo < hi then",
        "        let mid := (lo + hi) / 2",
        "        if (tbl[mid]!).2 < cp then go (mid + 1) hi fuel else go lo mid fuel",
        "      else lo",
        "  let i := go 0 tbl.size tbl.size",
        "  decide (i < tbl.size) && (tbl[i]!).1 ≤ cp",
        "",
        "/-- `c ∈ XID_Start`. -/",
        "def isXidStart (c : Char) : Bool := rangeTableContains xidStartRanges c.val",
        "",
        "/-- `c ∈ XID_Continue`. -/",
        "def isXidContinue (c : Char) : Bool := rangeTableContains xidContinueRanges c.val",
        "",
        "end UsdSpec.Unicode",
        "",
    ]
    return "\n".join(parts)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT, help="output .lean path")
    ap.add_argument("--check", action="store_true", help="diff against --out instead of writing; exit 1 on drift")
    ap.add_argument("--source", default=C_SOURCE, help="C table source")
    ap.add_argument("--ucd-dir", default=DEFAULT_UCD_DIR, help="verified UCD cache")
    args = ap.parse_args()
    with open(args.source, encoding="utf-8") as f:
        text = f.read()
    generated = generate(text, args.ucd_dir)
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            print(f"{args.out}: missing", file=sys.stderr)
            return 1
        if current != generated:
            import difflib
            sys.stdout.writelines(difflib.unified_diff(
                current.splitlines(True), generated.splitlines(True),
                fromfile=args.out, tofile="generated"))
            print(f"{args.out}: drift detected", file=sys.stderr)
            return 1
        print(f"{args.out}: up to date")
        return 0
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(generated)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
