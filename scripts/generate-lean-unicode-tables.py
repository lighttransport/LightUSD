#!/usr/bin/env python3
"""Generate verif/lean/UsdSpec/Unicode/NormTables.lean from Python's unicodedata.

Emits only what canonical normalization (NFD / NFC, UAX #15) needs:

* canonDecomp   : (cp, first, second) for every character with a *canonical*
                  decomposition mapping (second = 0 for singletons); Hangul
                  syllables are excluded (algorithmic, handled in Normalize.lean).
                  Mappings are one level (recursive application is in Lean).
* cccRanges     : (lo, hi, ccc) runs of equal non-zero canonical combining class.
* compositions  : (first * 2^21 + second, composite) for every primary composite
                  (canonical pair mapping that is not a full composition exclusion),
                  sorted by key.
* compExclusions: characters with a two-character canonical mapping that are
                  full-composition-excluded (CompositionExclusions.txt + non-starter
                  decompositions); documentation / cross-check only.

No case-folding table: the spec's element ordering (core_spec.md L3516-3531)
case-folds ASCII letters only and orders other characters by code point.

Run with the system interpreter in isolated mode (the Unicode version is that
of the interpreter's unicodedata and is recorded in the output header):

  python3 -I scripts/generate-lean-unicode-tables.py            # write default path
  python3 -I scripts/generate-lean-unicode-tables.py --out F    # write F
  python3 -I scripts/generate-lean-unicode-tables.py --check    # diff, exit 1 on drift
"""
import argparse
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "verif", "lean", "UsdSpec", "Unicode", "NormTables.lean")
SBASE, SCOUNT = 0xAC00, 11172


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp


def canonical_mapping(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def build():
    decomp, ccc, comps, excl = [], [], [], []
    for cp in chars():
        c = unicodedata.combining(chr(cp))
        if c:
            ccc.append((cp, c))
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        m = canonical_mapping(cp)
        if m is None:
            continue
        if len(m) > 2:
            raise SystemExit(f"U+{cp:04X}: canonical mapping longer than 2")
        decomp.append((cp, m[0], m[1] if len(m) == 2 else 0))
        if len(m) == 2:
            # Primary composite iff NFC of its mapping recomposes to it.
            if unicodedata.normalize("NFC", chr(m[0]) + chr(m[1])) == chr(cp):
                comps.append(((m[0] << 21) | m[1], cp))
            else:
                excl.append(cp)
    comps.sort()
    runs = []
    for cp, c in ccc:
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == c:
            runs[-1] = (runs[-1][0], cp, c)
        else:
            runs.append((cp, cp, c))
    return decomp, runs, comps, excl


def arr(name, doc, ty, rows, fmt):
    out = [f"/-- {doc} ({len(rows)} entries, sorted). -/", f"def {name} : Array ({ty}) := #["]
    for i, r in enumerate(rows):
        out.append("  " + fmt(r) + ("," if i + 1 < len(rows) else ""))
    out.append("]")
    return "\n".join(out)


def generate():
    decomp, runs, comps, excl = build()
    ver = unicodedata.unidata_version
    parts = [
        "-- Generated by scripts/generate-lean-unicode-tables.py. Do not edit.",
        f"-- Source: Python {sys.version_info.major}.{sys.version_info.minor} unicodedata, "
        f"Unicode {ver} (unicodedata.unidata_version).",
        "/-!",
        "# Unicode canonical normalization tables (UAX #15, NFD / NFC only)",
        "",
        f"Unicode version: {ver}. The spec cites Unicode 15.1.0 (core_spec.md L1013-1016);",
        "by the Unicode normalization stability policy every mapping of a 15.1",
        "character is unchanged in later versions, so only characters added after",
        "15.1 differ.",
        "",
        "Used by `UsdSpec.Unicode.Normalize`. The spec does not require normalization",
        "(core_spec.md L3903-3909); these tables exist to state what canonical",
        "equivalence would identify.",
        "-/",
        "",
        "namespace UsdSpec.Unicode.Norm",
        "",
        "set_option maxRecDepth 100000",
        "",
        arr("canonDecomp", "One-level canonical decomposition mappings `(cp, first, second or 0)`, Hangul excluded",
            "UInt32 × UInt32 × UInt32", decomp, lambda r: f"({r[0]:#x}, {r[1]:#x}, {r[2]:#x})"),
        "",
        arr("cccRanges", "Runs `(lo, hi, ccc)` of equal non-zero canonical combining class",
            "UInt32 × UInt32 × Nat", runs, lambda r: f"({r[0]:#x}, {r[1]:#x}, {r[2]})"),
        "",
        arr("compositions", "Primary composites `(first <<< 21 ||| second, composite)`, Hangul excluded",
            "UInt64 × UInt32", comps, lambda r: f"({r[0]:#x}, {r[1]:#x})"),
        "",
        arr("compExclusions", "Two-character canonical mappings that are full composition exclusions",
            "UInt32", excl, lambda r: f"{r:#x}"),
        "",
        f'def unicodeVersion : String := "{ver}"',
        "",
        "end UsdSpec.Unicode.Norm",
        "",
    ]
    return "\n".join(parts)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT, help="output .lean path")
    ap.add_argument("--check", action="store_true", help="diff against --out instead of writing; exit 1 on drift")
    args = ap.parse_args()
    generated = generate()
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != generated:
            print(f"DRIFT   {args.out}", file=sys.stderr)
            return 1
        print(f"ok      {args.out}")
        return 0
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(generated)
    print(f"wrote   {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
