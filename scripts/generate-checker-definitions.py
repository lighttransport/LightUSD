#!/usr/bin/env python3
"""Compile schema/shader JSON manifests into dependency-free checker tables.

Two artifacts are produced from the same JSON:

* a C11 data module under ``src/next/c`` (``generated-schema-tables.{c,h}``)
  consumed by the next product, and
* the rule metadata cross-check used by ``tools/lusdchecker``.

The C11 module is the next-side source of truth: it is compiled by the C
compiler with ``C_STANDARD 11``, so the ~1200-row schema inventory costs no C++
template instantiation and no static construction, and its text is a compact
string arena plus index rows instead of ``std::map`` build code.
"""
import argparse
import json
import re
from pathlib import Path


HEADER = r'''// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/generate-checker-definitions.py; do not edit.
// Schema provenance: {provenance}

#ifndef {guard}
#define {guard}

#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

/* Every string referenced below is an offset into lu_validation_strings(), a
 * NUL-terminated arena: no per-row allocation and no pointer relocation. */

/* One schema row. Rows are sorted by name for binary search, and their
 * properties occupy a contiguous, name-sorted range. */
typedef struct lu_validation_schema_row {{
  uint32_t name;
  uint32_t parent;
  uint32_t kind;
  uint32_t property_namespace;
  uint32_t source;
  uint32_t property_first;   /* index into lu_validation_property_rows */
  uint32_t property_count;
}} lu_validation_schema_row;

/* One property row within a schema's property range. */
typedef struct lu_validation_property_row {{
  uint32_t name;
  uint32_t type;
  uint32_t variability;
  uint32_t token_first;      /* index into lu_validation_token_offsets */
  uint32_t token_count;
  uint8_t is_relationship;
}} lu_validation_property_row;

/* One shader row, keyed by (identifier, source_type) and sorted by that key. */
typedef struct lu_validation_shader_row {{
  uint32_t identifier;
  uint32_t source_type;
  uint32_t source;
  uint32_t input_first;      /* index into lu_validation_shader_port_rows */
  uint32_t input_count;
  uint32_t output_first;
  uint32_t output_count;
}} lu_validation_shader_row;

typedef struct lu_validation_shader_port_row {{
  uint32_t name;
  uint32_t type;
}} lu_validation_shader_port_row;

/* One checker rule -> specification reference errors mapping, sorted by rule. */
typedef struct lu_validation_ref_error_row {{
  uint32_t rule;
  uint32_t first;            /* index into lu_validation_ref_error_offsets */
  uint32_t count;
}} lu_validation_ref_error_row;

extern const char lu_validation_strings[];
/* JSON provenance generated from the same manifests as these tables. */
extern const char lu_validation_schema_provenance[];
extern const uint32_t lu_validation_token_offsets[];
extern const size_t lu_validation_token_offset_count;
extern const uint32_t lu_validation_ref_error_offsets[];
extern const size_t lu_validation_ref_error_offset_count;

extern const lu_validation_schema_row lu_validation_schema_rows[];
extern const size_t lu_validation_schema_row_count;
extern const lu_validation_property_row lu_validation_property_rows[];
extern const size_t lu_validation_property_row_count;
extern const lu_validation_shader_row lu_validation_shader_rows[];
extern const size_t lu_validation_shader_row_count;
extern const lu_validation_shader_port_row lu_validation_shader_port_rows[];
extern const size_t lu_validation_shader_port_row_count;
extern const lu_validation_ref_error_row lu_validation_ref_error_rows[];
extern const size_t lu_validation_ref_error_row_count;

#ifdef __cplusplus
}}  /* extern "C" */
#endif

#endif  /* {guard} */
'''

ROW_TYPES = {
    'schema': ('lu_validation_schema_row', 'lu_validation_schema_rows',
               'lu_validation_schema_row_count'),
    'property': ('lu_validation_property_row', 'lu_validation_property_rows',
                 'lu_validation_property_row_count'),
    'shader': ('lu_validation_shader_row', 'lu_validation_shader_rows',
               'lu_validation_shader_row_count'),
    'shader_port': ('lu_validation_shader_port_row',
                    'lu_validation_shader_port_rows',
                    'lu_validation_shader_port_row_count'),
    'ref_error': ('lu_validation_ref_error_row',
                  'lu_validation_ref_error_rows',
                  'lu_validation_ref_error_row_count'),
}


def emit_c(schema, shader, references):
    """Return (header_text, source_text) for the C11 data module."""
    strings = []
    offsets = {}

    def off(text):
        text = text or ''
        if text not in offsets:
            offsets[text] = sum(len(s.encode('utf-8')) + 1 for s in strings)
            strings.append(text)
        return offsets[text]

    # Schemas, sorted by name. Duplicate names keep the last definition, which
    # matches the previous std::map-based destination.
    schemas = {}
    for s in schema['schemas']:
        schemas[s.get('name', '')] = s
    schema_rows = []
    property_rows = []
    token_offsets = []
    for name in sorted(schemas):
        s = schemas[name]
        # Property names within a schema: last definition wins, then sorted.
        props = {}
        for p in s.get('properties', []):
            props[p.get('name', '')] = p
        prop_first = len(property_rows)
        for pname in sorted(props):
            p = props[pname]
            tokens = [off(t) for t in p.get('allowedTokens', [])]
            token_first = len(token_offsets)
            token_offsets.extend(tokens)
            property_rows.append({
                'name': off(pname),
                'type': off(p.get('type', '')),
                'variability': off(p.get('variability', '')),
                'token_first': token_first,
                'token_count': len(tokens),
                'is_relationship': 1 if p.get('kind') == 'relationship' else 0,
            })
        schema_rows.append({
            'name': off(name),
            'parent': off(s.get('inherits', '')),
            'kind': off(s.get('kind', '')),
            'property_namespace': off(s.get('propertyNamespacePrefix', '')),
            'source': off(s.get('source', '')),
            'property_first': prop_first,
            'property_count': len(props),
        })

    # Shaders, sorted by (identifier, source_type); ports are sorted by name
    # exactly like the JSON dump they come from.
    shaders = {}
    for s in shader.get('shaders', []):
        shaders[(s.get('identifier', ''), s.get('sourceType', ''))] = s
    shader_rows = []
    port_rows = []
    for key in sorted(shaders):
        s = shaders[key]
        inputs = [(off(k), off(v)) for k, v in sorted(s.get('inputs', {}).items())]
        outputs = [(off(k), off(v)) for k, v in sorted(s.get('outputs', {}).items())]
        input_first = len(port_rows)
        port_rows.extend({'name': n, 'type': t} for n, t in inputs)
        output_first = len(port_rows)
        port_rows.extend({'name': n, 'type': t} for n, t in outputs)
        shader_rows.append({
            'identifier': off(key[0]),
            'source_type': off(key[1]),
            'source': off(s.get('source', '')),
            'input_first': input_first,
            'input_count': len(inputs),
            'output_first': output_first,
            'output_count': len(outputs),
        })

    # Rule -> reference errors, sorted by rule.
    reverse = {}
    for error, entry in references['errors'].items():
        for rule in entry['rules']:
            reverse.setdefault(rule, []).append(error)
    ref_rows = []
    ref_offsets = []
    for rule in sorted(reverse):
        errors = sorted(reverse[rule])
        first = len(ref_offsets)
        ref_offsets.extend(off(e) for e in errors)
        ref_rows.append({'rule': off(rule), 'first': first, 'count': len(errors)})

    source = ['// SPDX-License-Identifier: Apache-2.0',
              '// Generated by scripts/generate-checker-definitions.py; do not edit.',
              '// Schema provenance: ' + _provenance(schema),
              '',
              '#include "generated-schema-tables.h"',
              '',
              'const char lu_validation_schema_provenance[] = ' + json.dumps(_provenance(schema)) + ';',
              '',
              '/* NUL-separated UTF-8 arena, with no overlength C string literals. */',
              'const char lu_validation_strings[] = {']
    arena = b''.join(s.encode('utf-8') + b'\0' for s in strings) + b'\0'
    for i in range(0, len(arena), 24):
        source.append('    ' + ', '.join('(char)0x%02x' % b if b > 127 else str(b)
                                       for b in arena[i:i + 24]) + ',')
    source.append('};')
    source.append('')

    source.append('const uint32_t lu_validation_token_offsets[] = {')
    for i in range(0, len(token_offsets), 8):
        source.append('    ' + ', '.join('%du' % v for v in token_offsets[i:i + 8]) + ',')
    source.append('};')
    source.append('const size_t lu_validation_token_offset_count = %du;' % len(token_offsets))
    source.append('const uint32_t lu_validation_ref_error_offsets[] = {')
    for i in range(0, len(ref_offsets), 8):
        source.append('    ' + ', '.join('%du' % v for v in ref_offsets[i:i + 8]) + ',')
    source.append('};')
    source.append('const size_t lu_validation_ref_error_offset_count = %du;' % len(ref_offsets))
    source.append('')

    for kind, rows in (('schema', schema_rows), ('property', property_rows),
                       ('shader', shader_rows), ('shader_port', port_rows),
                       ('ref_error', ref_rows)):
        struct, array, count = ROW_TYPES[kind]
        source.append('const %s %s[] = {' % (struct, array))
        for row in rows:
            fields = ', '.join('%du' % v if isinstance(v, int) else '%du' % v
                               for v in _fields(kind, row))
            source.append('    {%s},' % fields)
        source.append('};')
        source.append('const size_t %s = %du;' % (count, len(rows)))
        source.append('')

    header = HEADER.format(
        provenance=_provenance(schema),
        guard='LIGHTUSD_C_GENERATED_SCHEMA_TABLES_H_')
    return header, '\n'.join(source) + '\n'


def _provenance(schema):
    return json.dumps({'openusd': schema.get('openusd', {}),
                       'engines': schema.get('engines', {})}, sort_keys=True)


def _fields(kind, row):
    if kind == 'schema':
        return (row['name'], row['parent'], row['kind'],
                row['property_namespace'], row['source'],
                row['property_first'], row['property_count'])
    if kind == 'property':
        return (row['name'], row['type'], row['variability'],
                row['token_first'], row['token_count'],
                row['is_relationship'])
    if kind == 'shader':
        return (row['identifier'], row['source_type'], row['source'],
                row['input_first'], row['input_count'],
                row['output_first'], row['output_count'])
    if kind == 'shader_port':
        return (row['name'], row['type'])
    if kind == 'ref_error':
        return (row['rule'], row['first'], row['count'])
    raise AssertionError(kind)


def main():
    root = Path(__file__).resolve().parents[1]
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--schemas', type=Path,
                   default=root / 'doc/generated/openusd-schema-26.08.json')
    p.add_argument('--engine-schemas', type=Path,
                   default=root / 'doc/generated/engine-physics-schemas.json',
                   help='versioned Newton/MuJoCo schema manifest merged into '
                        'the schema tables (pass an empty path to omit)')
    p.add_argument('--shaders', type=Path,
                   default=root / 'tools/lusdchecker/definitions/shaders.json')
    p.add_argument('--references', type=Path,
                   default=root / 'tools/lusdchecker/reference-errors.json')
    p.add_argument('--output', type=Path,
                   default=root / 'src/next/c/generated-schema-tables.c')
    p.add_argument('--header', type=Path,
                   default=root / 'src/next/c/generated-schema-tables.h')
    p.add_argument('--rule-table', type=Path,
                   default=root / 'src/next/validation/usd-validation-report.cc')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()

    schema = json.loads(a.schemas.read_text())
    if a.engine_schemas and str(a.engine_schemas) and a.engine_schemas.is_file():
        engines = json.loads(a.engine_schemas.read_text())
        names = {s.get('name') for s in schema['schemas']}
        clash = sorted(names & {s.get('name') for s in engines['schemas']})
        if clash:
            p.error('engine schemas shadow OpenUSD schemas: ' + ', '.join(clash))
        schema = dict(schema)
        schema['schemas'] = list(schema['schemas']) + list(engines['schemas'])
        schema['engines'] = engines.get('engines', {})
    shader = json.loads(a.shaders.read_text())
    references = json.loads(a.references.read_text())
    header, source = emit_c(schema, shader, references)

    registered = set(re.findall(r'\{"([^" ]+)", "[a-z]+"', a.rule_table.read_text()))
    mapped = {rule for entry in references['errors'].values() for rule in entry['rules']}
    if mapped - registered:
        p.error('reference mapping contains unregistered rules: '
                + ', '.join(sorted(mapped - registered)))

    outputs = ((a.output, source), (a.header, header))
    if a.check:
        for path, text in outputs:
            if not path.exists() or path.read_text() != text:
                p.error('%s is stale; run the generator' % path)
    else:
        for path, text in outputs:
            path.write_text(text)


if __name__ == '__main__':
    main()
