/* Rows are sorted by the inclusive upper bound; a codepoint is in a range when
 * it falls in the first row whose end >= it and whose begin <= it. */
static int in_table(const unsigned int (*table)[2], unsigned int n,
                    unsigned int cp) {
  if (cp > LU_XID_MAX_CODEPOINT) return 0;
  unsigned int lo = 0, hi = n;
  while (lo < hi) {
    const unsigned int mid = lo + (hi - lo) / 2;
    if (table[mid][1] < cp) {
      lo = mid + 1;
    } else {
      hi = mid;
    }
  }
  return lo < n && cp >= table[lo][0];
}

int unicode_xid_is_start(unsigned int codepoint) {
  return in_table(kXID_StartTable,
                  (unsigned int)(sizeof(kXID_StartTable) /
                                 sizeof(kXID_StartTable[0])),
                  codepoint);
}

int unicode_xid_is_continue(unsigned int codepoint) {
  return in_table(kXID_ContinueTable,
                  (unsigned int)(sizeof(kXID_ContinueTable) /
                                 sizeof(kXID_ContinueTable[0])),
                  codepoint);
}
